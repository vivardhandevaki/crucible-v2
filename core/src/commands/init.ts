// `crucible init` — install a complete, working Crucible setup into a repo
// (charter §Configuration; design phase-2.md §7). init is the one command that
// WRITES the trusted-computing-base files a project is then governed by — the
// enforcement config, the schema bundles, the reviewer rubric, the role prompts,
// and the CI workflow — plus the convenience defaults and the managed agent
// block. Everything downstream (propose/approve/implement/verify) presupposes
// these files exist and validate; init is where they come from.
//
// Two properties are load-bearing:
//
//   1. It installs from SHIPPED SOURCES OF TRUTH, never hand-rolled strings:
//      the schema bundles come from `@crucible/schemas`, the CI workflow from
//      `@crucible/ci-templates`, the rubric + role prompts + convenience default
//      from `core/assets/`. `crucible doctor` (P2-13) later checks a project's
//      copies against these same sources — so init and doctor share one notion
//      of "the shipped version".
//
//   2. It NEVER silently overwrites (design §7 "re-run = diff-and-confirm"). A
//      fresh file is written; an identical file is left alone; a file that
//      exists with DIFFERENT bytes is only replaced if the caller confirms
//      (`confirmOverwrite`, the one injected decision edge — the CLI shows the
//      diff and reads y/N, tests script it). The gitignore + managed-block +
//      openspec-config surfaces are edited additively/in-region, so re-running
//      init on an already-initialized repo is a no-op that reports `unchanged`.
//
// The managed CLAUDE.md / AGENTS.md block is written with Crucible's OWN
// marker-delimited mechanism, replaced in place on re-run. (This intentionally
// does NOT use "OpenSpec's regeneration mechanism" the charter §267 aside names:
// the spike proved `openspec update` regenerates only `.claude/` integration
// files and never touches CLAUDE.md/AGENTS.md — see design phase-2.md §7. The
// design doc records this amendment.)
//
// Determinism (invariant 12): given the same repo state + `answers` + confirm
// decisions, init produces the same files and the same report. The interactive
// parts (adapter detection, the unit-test command, the y/N prompts) are resolved
// by the CLI into `answers` + `confirmOverwrite` before the core runs.

